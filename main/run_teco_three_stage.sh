    save_model_output \
        "${SIM_OUTPUT}" \
        "${RUN_DIR}/stage3_P${P_RATE}"

done

echo "========================================"
echo "All three stages completed successfully."
echo "Results:"
echo "${RUN_DIR}"
echo "========================================"